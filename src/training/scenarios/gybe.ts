import type { Cond, ScenarioDef } from './types';
import { REVIEW_NOTE, safetyRules, t, type Dir } from './common';

/**
 * Dead run: the wind is (nearly) straight astern, the jib is blanketed by the main and collapses,
 * and the boom is about to come across. (The simulator does not model the wind shadow itself, so the
 * true wind angle is used.)
 */
export const DEAD_RUN = (target: 'port' | 'starboard'): Cond => ({ any: [{ twaAbs: { min: 165 } }, { tack: target }] });

export function buildGybe(dir: Dir = 'starboardToPort'): ScenarioDef {
  const fromStbd = dir === 'starboardToPort';
  const target = fromStbd ? 'port' : 'starboard';
  const turn = fromStbd ? t('שמאלה', 'to port') : t('ימינה', 'to starboard');
  const fromName = fromStbd ? t('מפנה ימני', 'starboard tack') : t('מפנה שמאלי', 'port tack');
  const toName = fromStbd ? t('מפנה שמאלי', 'port tack') : t('מפנה ימני', 'starboard tack');
  return {
    id: 'gybe',
    variant: dir,
    title: t('מהפך מבוקר', 'Controlled gybe'),
    objective: t(`בצע מהפך מבוקר מ${fromName.he} ל${toName.he} והתייצב בגבית חלקית.`, `Perform a controlled gybe from ${fromName.en} to ${toName.en} and settle on a broad reach.`),
    learningObjective: t(
      'במהפך הירכתיים עוברים דרך הרוח והבום עובר צד. מוודאים שימין, שמאל וראשי מוכנים, ממרכזים את הראשי לפני הפנייה, קוראים "דד רן" כשהחלוץ קורס ומעבירים את החלוץ.',
      'In a gybe the stern passes through the wind and the boom changes sides. Check starboard, port and main are ready, centre the main before turning, call "Dead run" when the jib collapses, then switch the jib.',
    ),
    initial: {
      heading: 0,
      speed: 5.5,
      wind: { trueFrom: fromStbd ? 145 : 215, trueSpeed: 14 },
      mainHoist: 1,
      mainsheet: 0.1,
      jibDeployed: 1,
      jibPortSheet: fromStbd ? 0.2 : 0,
      jibStarboardSheet: fromStbd ? 0 : 0.2,
      autoTrim: true,
    },
    steps: [
      {
        id: 'prepare',
        title: t('"היכון למהפך"', '"Prepare to gybe"'),
        hint: t('תן פקודה "היכון למהפך". הצוות מתכונן: שוטי החלוץ בידיים ושוט הראשי מוכן למשיכה.', 'Command "Prepare to gybe". The crew gets ready: jib sheets in hand and the mainsheet ready to pull in.'),
        done: { crewReady: 'gybe' },
        optional: true,
        highlight: ['prepareGybe'],
        source: 'school',
      },
      {
        id: 'checkStarboard',
        title: t('"ימין מוכן?" – "מוכן!"', '"Starboard ready?" – "Ready!"'),
        hint: t('שאל את הצוות בצד ימין אם הוא מוכן, והמתן ל"מוכן".', 'Ask the starboard-side crew if they are ready and wait for "Ready".'),
        done: { event: 'crewReport', data: { side: 'starboard', ready: true } },
        optional: true,
        highlight: ['checkStarboardReady'],
        source: 'school',
      },
      {
        id: 'checkPort',
        title: t('"שמאל מוכן?" – "מוכן!"', '"Port ready?" – "Ready!"'),
        hint: t('שאל את הצוות בצד שמאל אם הוא מוכן, והמתן ל"מוכן".', 'Ask the port-side crew if they are ready and wait for "Ready".'),
        done: { event: 'crewReport', data: { side: 'port', ready: true } },
        optional: true,
        highlight: ['checkPortReady'],
        source: 'school',
      },
      {
        id: 'checkMain',
        title: t('"ראשי מוכן?" – "מוכן!"', '"Main ready?" – "Ready!"'),
        hint: t('שאל את מי שעל שוט הראשי אם הוא מוכן, והמתן ל"מוכן".', 'Ask the mainsheet trimmer if they are ready and wait for "Ready".'),
        done: { event: 'crewReport', data: { side: 'main', ready: true } },
        optional: true,
        highlight: ['checkMainReady'],
        source: 'school',
      },
      {
        id: 'centerMain',
        title: t('מתח את הראשי למרכז', 'Pull the main in to the centre'),
        hint: t('תן "מרכז ראשי" (או מתח ידנית) – לפני שמתחילים לפנות. ראשי ממורכז = הבום יעבור בשליטה.', 'Command "Centre main" (or trim by hand) – before you start turning. A centred main means the boom crosses under control.'),
        done: { mainsheet: { min: 0.75 } },
        highlight: ['centerMain', 'mainsheet'],
        source: 'school',
      },
      {
        id: 'announce',
        title: t('"מהפך" – סובב את ההגה למורד הרוח', '"Gybing" – turn the wheel downwind'),
        hint: t(`הכרז "מהפך" וסובב את ההגה ${turn.he} באיטיות – הירכתיים מתקרבים לרוח.`, `Call "Gybing" and turn the wheel ${turn.en} gently – the stern comes towards the wind.`),
        done: { all: [{ command: 'gybe' }, { rudderAbs: { min: 5 } }] },
        optional: true,
        highlight: ['gybe', 'helm'],
        source: 'school',
      },
      {
        id: 'deadRun',
        title: t('"דד רן" – כשהחלוץ קורס', '"Dead run" – when the jib collapses'),
        hint: t('כשהרוח בדיוק מאחור החלוץ נכנס לצל של הראשי וקורס. זה הרגע לקרוא "דד רן" – הבום עומד לעבור, ראשים למטה.', 'With the wind dead astern the jib falls into the shadow of the main and collapses. That is the moment to call "Dead run" – the boom is about to come over, heads down.'),
        done: { all: [{ command: 'deadRun' }, DEAD_RUN(target)] },
        highlight: ['deadRun', 'helm'],
        source: 'school',
      },
      {
        id: 'switchJib',
        title: t('"העבר חלוץ!"', '"Switch jib!"'),
        hint: t('תן "העבר חלוץ!" – צד אחד משחרר והשני מושך. המשך לפנות מעט עד שהבום והחלוץ עוברים לצד החדש.', 'Command "Switch jib!" – one side releases, the other pulls. Keep turning a little until the boom and the jib are on the new side.'),
        done: { all: [{ tack: target }, { boomSide: 'leeward' }, { jibSide: 'leeward' }, { jibBacked: false }] },
        highlight: ['switchJib', 'helm'],
        source: 'school',
      },
      {
        id: 'trimEase',
        title: t('מתח את החלוץ ושחרר את הראשי', 'Trim the jib and ease the main'),
        hint: t('מתח את החלוץ בצד החדש עד שהוא מלא, ושחרר את הראשי ("שחרר ראשי") לגבית. החזר את ההגה למרכז.', 'Trim the jib on the new side until it is full, and ease the main ("Ease main") for the broad reach. Centre the wheel.'),
        done: { all: [{ mainTrim: { min: 0.55 } }, { jibTrim: { min: 0.6 } }] },
        holdSeconds: 1,
        highlight: ['easeMain', fromStbd ? 'trimJibStarboard' : 'trimJibPort', 'helmCenter'],
        source: 'school',
      },
      {
        id: 'settle',
        title: t('התייצב בגבית חלקית', 'Settle on a broad reach'),
        hint: t('שמור על כיוון יציב, כ-140° לרוח.', 'Hold a steady course about 140° off the wind.'),
        done: { all: [{ tack: target }, { twaAbs: { min: 120, max: 170 } }, { yawRateAbs: { max: 2.5 } }] },
        holdSeconds: 3,
        highlight: ['helmCenter'],
        source: 'general',
      },
    ],
    success: {
      cond: { all: [{ tack: target }, { twaAbs: { min: 120, max: 170 } }, { mainTrim: { min: 0.5 } }, { boomSide: 'leeward' }, { yawRateAbs: { max: 2.5 } }] },
      holdSeconds: 4,
    },
    timeLimit: 120,
    rules: [
      ...safetyRules(),
      {
        id: 'noPrepare',
        type: 'requireBefore',
        event: 'boomChangedSide',
        require: { command: 'prepareGybe' },
        category: 'crew',
        area: 'crew',
        penalty: 20,
        source: 'school',
        message: t('המהפך בוצע בלי "היכון למהפך".', 'Gybed without "Prepare to gybe".'),
        explanation: t('הצוות חייב לדעת שהבום עומד לעבור – סכנת פגיעה בראש.', 'The crew must know the boom is about to cross – risk of head injury.'),
        suggestion: t('תן "היכון למהפך" והמתן ל"מוכן".', 'Call "Prepare to gybe" and wait for "Ready".'),
      },
      {
        id: 'noSideCheck',
        type: 'requireBefore',
        event: 'crewCommand',
        eventData: { command: 'gybe' },
        require: {
          all: [
            { event: 'crewReport', data: { side: 'starboard', ready: true } },
            { event: 'crewReport', data: { side: 'port', ready: true } },
            { event: 'crewReport', data: { side: 'main', ready: true } },
          ],
        },
        category: 'crew',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('הכרזת "מהפך" לפני שימין, שמאל וראשי ענו "מוכן".', 'Called "Gybing" before starboard, port and main answered "Ready".'),
        explanation: t('במהפך שלוש עמדות עובדות יחד: שני שוטי החלוץ ושוט הראשי. כל אחת חייבת להיות מוכנה.', 'In a gybe three stations work together: both jib sheets and the mainsheet. Each must be ready.'),
        suggestion: t('שאל "ימין מוכן?", "שמאל מוכן?", "ראשי מוכן?" והמתן ל"מוכן" מכל אחד.', 'Ask "Starboard ready?", "Port ready?", "Main ready?" and wait for "Ready" from each.'),
      },
      {
        id: 'turnBeforeCentre',
        type: 'checkAtEvent',
        event: 'crewCommand',
        eventData: { command: 'gybe' },
        require: { mainsheet: { min: 0.6 } },
        category: 'procedural',
        area: 'sails',
        penalty: 10,
        source: 'school',
        message: t('הכרזת "מהפך" לפני שהראשי מורכז.', 'Called "Gybing" before the main was centred.'),
        explanation: t('את הראשי מושכים למרכז לפני שמתחילים לפנות, כדי שלא יעבור בפתאומיות.', 'The main is pulled in to the centre before you start turning, so it cannot slam across.'),
        suggestion: t('"מרכז ראשי" – ורק אז "מהפך".', '"Centre main" – and only then "Gybing".'),
      },
      {
        id: 'earlyDeadRun',
        type: 'checkAtEvent',
        event: 'crewCommand',
        eventData: { command: 'deadRun' },
        require: { any: [{ twaAbs: { min: 160 } }, { tack: target }] },
        category: 'timing',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('"דד רן" נקרא לפני שהרוח הגיעה מאחור.', '"Dead run" was called before the wind was astern.'),
        explanation: t('"דד רן" מסמן לצוות שהבום עומד לעבור. קריאה מוקדמת מבלבלת את הצוות.', '"Dead run" tells the crew the boom is about to come over. An early call confuses the crew.'),
        suggestion: t('קרא "דד רן" כשהרוח בדיוק מאחור והחלוץ קורס.', 'Call "Dead run" when the wind is dead astern and the jib collapses.'),
      },
      {
        id: 'noDeadRun',
        type: 'requireBefore',
        event: 'boomChangedSide',
        require: { command: 'deadRun' },
        category: 'crew',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('הבום עבר בלי קריאת "דד רן".', 'The boom came across without a "Dead run" call.'),
        explanation: t('בלי הקריאה הצוות לא יודע שהבום עומד לעבור – סכנת פגיעה בראש.', 'Without the call the crew does not know the boom is about to cross – risk of a head injury.'),
        suggestion: t('כשהחלוץ קורס ברוח גבית – "דד רן!".', 'When the jib collapses on the run – "Dead run!".'),
      },
      {
        id: 'earlySwitch',
        type: 'checkAtEvent',
        event: 'crewCommand',
        eventData: { command: 'switchJib' },
        require: { all: [{ command: 'deadRun' }, DEAD_RUN(target)] },
        category: 'timing',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('"העבר חלוץ" ניתן לפני "דד רן".', '"Switch jib" was called before "Dead run".'),
        explanation: t('את החלוץ מעבירים רק אחרי שקרס ברוח גבית; לפני כן הוא עדיין עובד.', 'The jib is switched only after it collapses on the run; before that it is still drawing.'),
        suggestion: t('הסדר: "מהפך" → "דד רן" → "העבר חלוץ".', 'The order: "Gybing" → "Dead run" → "Switch jib".'),
      },
      {
        id: 'noSwitchCall',
        type: 'atEnd',
        require: { command: 'switchJib' },
        category: 'procedural',
        area: 'crew',
        penalty: 5,
        source: 'school',
        message: t('לא ניתנה פקודת "העבר חלוץ".', 'No "Switch jib" call was given.'),
        explanation: t('הפקודה מתאמת בין הצד שמשחרר לצד שמושך.', 'The call coordinates the side that releases with the side that pulls.'),
        suggestion: t('אחרי "דד רן" – "העבר חלוץ!".', 'After "Dead run" – "Switch jib!".'),
      },
      {
        id: 'mainNotCentred',
        type: 'checkAtEvent',
        event: 'boomChangedSide',
        require: { mainsheet: { min: 0.6 } },
        category: 'sail',
        area: 'sails',
        penalty: 15,
        source: 'general',
        message: t('הבום עבר כשהראשי לא ממורכז.', 'The boom crossed with the main not centred.'),
        explanation: t('ככל שהשוט ארוך יותר, הבום עובר קשת גדולה יותר ומהר יותר.', 'The longer the sheet, the further and faster the boom travels.'),
        suggestion: t('מרכז את הראשי לפני שהירכתיים עוברים את הרוח.', 'Centre the main before the stern passes through the wind.'),
      },
      {
        id: 'roundUp',
        type: 'condDuration',
        after: 'boomChangedSide',
        cond: { twaAbs: { max: 105 } },
        seconds: 3,
        category: 'steering',
        area: 'steering',
        penalty: 15,
        source: 'general',
        message: t('הסירה התקרבה מדי לרוח אחרי המהפך.', 'The boat rounded up after the gybe.'),
        explanation: t('אחרי מעבר הבום הסירה נוטה להסתובב אל הרוח. יש לייצב בהגה.', 'After the boom crosses the boat tends to round up. Counter-steer to stabilise.'),
        suggestion: t('ברגע שהבום עובר – החזר את ההגה למרכז ואף מעט נגד.', 'As the boom crosses, centre the wheel and counter-steer slightly.'),
      },
      {
        id: 'wrongWay',
        type: 'forbidEvent',
        event: 'tackChanged',
        eventData: { through: 'bow' },
        category: 'procedural',
        area: 'completion',
        penalty: 30,
        source: 'general',
        message: t('החלפת מפנה דרך החרטום – זה סיבוב, לא מהפך.', 'You changed tack through the bow – that is a tack, not a gybe.'),
        explanation: t('במהפך הירכתיים עוברים את הרוח.', 'In a gybe the stern passes through the wind.'),
        suggestion: t(`במהפך מ${fromName.he} פנה ${turn.he}.`, `When gybing from ${fromName.en}, turn ${turn.en}.`),
      },
    ],
    commonErrors: [
      t('השארת הראשי משוחרר – מהפך לא מבוקר.', 'Leaving the main eased – uncontrolled gybe.'),
      t('פנייה מהירה מדי – הסירה "מסתובבת" לרוח.', 'Turning too fast – the boat rounds up.'),
      t('פנייה לפני שהראשי מורכז.', 'Turning before the main is centred.'),
      t('שכחת "דד רן" – הצוות לא מוכן למעבר הבום.', 'Forgetting "Dead run" – the crew is not ready for the boom.'),
      t('שכחה להעביר את החלוץ.', 'Forgetting to move the jib across.'),
    ],
    review: { status: 'needsInstructorReview', notes: [REVIEW_NOTE, 'Command sequence given by the project owner (2026-11-27): "היכון למהפך" → "ימין מוכן" / "שמאל מוכן" / "ראשי מוכן" → centre the main → "מהפך" (helm downwind) → "דד רן" (when the jib collapses) → "העבר חלוץ" → trim the jib and ease the main. Still to be confirmed by a qualified instructor.', 'The jib collapsing in the main\'s wind shadow is not modelled; "dead run" is detected from the true wind angle (165° or more).', 'Preventer, traveller and running backstays are not modelled.'] },
  };
}
