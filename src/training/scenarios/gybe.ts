import type { ScenarioDef } from './types';
import { REVIEW_NOTE, safetyRules, t, type Dir } from './common';

export function buildGybe(dir: Dir = 'starboardToPort'): ScenarioDef {
  const fromStbd = dir === 'starboardToPort';
  const target = fromStbd ? 'port' : 'starboard';
  const turn = fromStbd ? t('שמאלה', 'to port') : t('ימינה', 'to starboard');
  const fromName = fromStbd ? t('מפנה ימני', 'starboard tack') : t('מפנה שמאלי', 'port tack');
  const toName = fromStbd ? t('מפנה שמאלי', 'port tack') : t('מפנה ימני', 'starboard tack');
  return {
    id: 'gybe',
    variant: dir,
    title: t('מהפך מבוקר', 'Controlled gybe'),
    objective: t(`בצע מהפך מבוקר מ${fromName.he} ל${toName.he} והתייצב בגבית חלקית.`, `Perform a controlled gybe from ${fromName.en} to ${toName.en} and settle on a broad reach.`),
    learningObjective: t(
      'במהפך הירכתיים עוברים דרך הרוח והבום עובר צד. מרכזים את הראשי לפני המעבר כדי שהבום יעבור בשליטה.',
      'In a gybe the stern passes through the wind and the boom changes sides. Centre the mainsail first so the boom crosses under control.',
    ),
    initial: {
      heading: 0,
      speed: 5.5,
      wind: { trueFrom: fromStbd ? 145 : 215, trueSpeed: 14 },
      mainHoist: 1,
      mainsheet: 0.1,
      jibDeployed: 1,
      jibPortSheet: fromStbd ? 0.2 : 0,
      jibStarboardSheet: fromStbd ? 0 : 0.2,
      autoTrim: true,
    },
    steps: [
      {
        id: 'prepare',
        title: t('הכן את הצוות', 'Prepare the crew'),
        hint: t('תן פקודה "היכון למהפך" והמתן לאישור.', 'Command "Prepare to gybe" and wait for the crew.'),
        done: { crewReady: 'gybe' },
        optional: true,
        highlight: ['prepareGybe'],
        source: 'school',
      },
      {
        id: 'centerMain',
        title: t('מרכז את הראשי', 'Centre the mainsail'),
        hint: t('תן "מהפך" – הצוות ימשוך את שוט הראשי למרכז. אפשר גם "מרכז ראשי" או למתוח ידנית.', 'Command "Gybe" – the crew sheets the main to the centre. You can also use "Centre main" or trim manually.'),
        done: { mainsheet: { min: 0.75 } },
        highlight: ['gybe', 'centerMain', 'mainsheet'],
        source: 'general',
      },
      {
        id: 'bearAway',
        title: t('התרחק מהרוח לגבית מלאה', 'Bear away to a run'),
        hint: t(`סובב את ההגה ${turn.he} באיטיות עד שהרוח מגיעה מאחור.`, `Turn the wheel ${turn.en} gently until the wind is from astern.`),
        done: { twaAbs: { min: 168 } },
        highlight: ['helm'],
        source: 'general',
      },
      {
        id: 'boomCross',
        title: t('העבר את הבום', 'Bring the boom across'),
        hint: t('המשך לפנות מעט עד שהבום עובר לצד השני. הראשי ממורכז – הבום עובר בשליטה.', 'Keep turning slightly until the boom crosses. With the main centred it crosses under control.'),
        done: { all: [{ tack: target }, { boomSide: 'leeward' }] },
        highlight: ['helm'],
        source: 'general',
      },
      {
        id: 'easeMain',
        title: t('שחרר את הראשי בצד החדש', 'Ease the main on the new side'),
        hint: t('שחרר את הראשי לגבית ("שחרר ראשי"/ידנית) והתייצב בכיוון.', 'Ease the main for the broad reach (crew or manual) and steady the helm.'),
        done: { mainTrim: { min: 0.55 } },
        highlight: ['mainsheet', 'helmCenter'],
        source: 'general',
      },
      {
        id: 'jib',
        title: t('העבר את החלוץ', 'Move the jib across'),
        hint: t('שחרר את השוט הישן ומתח את השוט בצד הרחוק מהרוח.', 'Release the old sheet and trim the new leeward sheet.'),
        done: { all: [{ jibSide: 'leeward' }, { jibBacked: false }] },
        optional: true,
        highlight: [fromStbd ? 'trimJibStarboard' : 'trimJibPort'],
        source: 'general',
      },
      {
        id: 'settle',
        title: t('התייצב בגבית חלקית', 'Settle on a broad reach'),
        hint: t('שמור על כיוון יציב, כ-140° לרוח.', 'Hold a steady course about 140° off the wind.'),
        done: { all: [{ tack: target }, { twaAbs: { min: 120, max: 170 } }, { yawRateAbs: { max: 2.5 } }] },
        holdSeconds: 3,
        highlight: ['helmCenter'],
        source: 'general',
      },
    ],
    success: {
      cond: { all: [{ tack: target }, { twaAbs: { min: 120, max: 170 } }, { mainTrim: { min: 0.5 } }, { boomSide: 'leeward' }, { yawRateAbs: { max: 2.5 } }] },
      holdSeconds: 4,
    },
    timeLimit: 120,
    rules: [
      ...safetyRules(),
      {
        id: 'noPrepare',
        type: 'requireBefore',
        event: 'boomChangedSide',
        require: { command: 'prepareGybe' },
        category: 'crew',
        area: 'crew',
        penalty: 20,
        source: 'school',
        message: t('המהפך בוצע בלי "היכון למהפך".', 'Gybed without "Prepare to gybe".'),
        explanation: t('הצוות חייב לדעת שהבום עומד לעבור – סכנת פגיעה בראש.', 'The crew must know the boom is about to cross – risk of head injury.'),
        suggestion: t('תן "היכון למהפך" והמתן ל"מוכן".', 'Call "Prepare to gybe" and wait for "Ready".'),
      },
      {
        id: 'mainNotCentred',
        type: 'checkAtEvent',
        event: 'boomChangedSide',
        require: { mainsheet: { min: 0.6 } },
        category: 'sail',
        area: 'sails',
        penalty: 15,
        source: 'general',
        message: t('הבום עבר כשהראשי לא ממורכז.', 'The boom crossed with the main not centred.'),
        explanation: t('ככל שהשוט ארוך יותר, הבום עובר קשת גדולה יותר ומהר יותר.', 'The longer the sheet, the further and faster the boom travels.'),
        suggestion: t('מרכז את הראשי לפני שהירכתיים עוברים את הרוח.', 'Centre the main before the stern passes through the wind.'),
      },
      {
        id: 'roundUp',
        type: 'condDuration',
        after: 'boomChangedSide',
        cond: { twaAbs: { max: 105 } },
        seconds: 3,
        category: 'steering',
        area: 'steering',
        penalty: 15,
        source: 'general',
        message: t('הסירה התקרבה מדי לרוח אחרי המהפך.', 'The boat rounded up after the gybe.'),
        explanation: t('אחרי מעבר הבום הסירה נוטה להסתובב אל הרוח. יש לייצב בהגה.', 'After the boom crosses the boat tends to round up. Counter-steer to stabilise.'),
        suggestion: t('ברגע שהבום עובר – החזר את ההגה למרכז ואף מעט נגד.', 'As the boom crosses, centre the wheel and counter-steer slightly.'),
      },
      {
        id: 'wrongWay',
        type: 'forbidEvent',
        event: 'tackChanged',
        eventData: { through: 'bow' },
        category: 'procedural',
        area: 'completion',
        penalty: 30,
        source: 'general',
        message: t('החלפת מפנה דרך החרטום – זה סיבוב, לא מהפך.', 'You changed tack through the bow – that is a tack, not a gybe.'),
        explanation: t('במהפך הירכתיים עוברים את הרוח.', 'In a gybe the stern passes through the wind.'),
        suggestion: t(`במהפך מ${fromName.he} פנה ${turn.he}.`, `When gybing from ${fromName.en}, turn ${turn.en}.`),
      },
    ],
    commonErrors: [
      t('השארת הראשי משוחרר – מהפך לא מבוקר.', 'Leaving the main eased – uncontrolled gybe.'),
      t('פנייה מהירה מדי – הסירה "מסתובבת" לרוח.', 'Turning too fast – the boat rounds up.'),
      t('שכחה להעביר את החלוץ.', 'Forgetting to move the jib across.'),
    ],
    review: { status: 'needsInstructorReview', notes: [REVIEW_NOTE, 'Preventer, traveller and running backstays are not modelled.'] },
  };
}
