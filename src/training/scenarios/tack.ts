import type { ScenarioDef } from './types';
import type { Cond } from './types';
import { REVIEW_NOTE, safetyRules, t, type Dir } from './common';

/**
 * The jib has "collapsed": the bow is close enough to the wind that the jib is flapping (or is already
 * aback, or the bow has crossed). "העבר חלוץ!" should not be called before this.
 */
export const JIB_COLLAPSED = (target: 'port' | 'starboard'): Cond => ({
  any: [{ jibLuff: { min: 0.7 } }, { awaAbs: { max: 20 } }, { jibBacked: true }, { tack: target }],
});

export function buildTack(dir: Dir = 'starboardToPort'): ScenarioDef {
  const fromStbd = dir === 'starboardToPort';
  const target = fromStbd ? 'port' : 'starboard';
  const turn = fromStbd ? t('ימינה', 'to starboard') : t('שמאלה', 'to port');
  const fromName = fromStbd ? t('מפנה ימני', 'starboard tack') : t('מפנה שמאלי', 'port tack');
  const toName = fromStbd ? t('מפנה שמאלי', 'port tack') : t('מפנה ימני', 'starboard tack');
  const oldSheet = fromStbd ? t('השמאלי', 'port') : t('הימני', 'starboard');
  const newSheet = fromStbd ? t('הימני', 'starboard') : t('השמאלי', 'port');
  return {
    id: 'tack',
    variant: dir,
    title: t('סיבוב', 'Tacking'),
    objective: t(`עליך לבצע סיבוב מ${fromName.he} ל${toName.he}.`, `Tack from ${fromName.en} to ${toName.en}.`),
    learningObjective: t(
      'בסיבוב החרטום עובר דרך הרוח. מכינים את הצוות ומוודאים שכל צד מוכן, עולים לרוח בפנייה רציפה, ומעבירים את החלוץ רק כשהוא קורס מול הרוח.',
      'In a tack the bow passes through the wind. Prepare the crew and check each side is ready, head up with a steady turn, and switch the jib only once it collapses head to wind.',
    ),
    initial: {
      heading: 0,
      speed: 5.5,
      wind: { trueFrom: fromStbd ? 45 : 315, trueSpeed: 12 },
      mainHoist: 1,
      mainsheet: 0.9,
      jibDeployed: 1,
      jibPortSheet: fromStbd ? 1 : 0,
      jibStarboardSheet: fromStbd ? 0 : 1,
      autoTrim: true,
    },
    steps: [
      {
        id: 'prepare',
        title: t('"הצוות, היכון לסיבוב"', '"Crew, ready about"'),
        hint: t('תן פקודה "הצוות, היכון לסיבוב". הצוות מכין את השוט החדש על הכננת ומחזיק את השוט הישן מוכן לשחרור.', 'Command "Crew, ready about". The crew puts the new sheet on its winch and gets ready to release the old one.'),
        done: { crewReady: 'tack' },
        optional: true,
        highlight: ['prepareTack'],
        source: 'school',
      },
      {
        id: 'checkStarboard',
        title: t('"צד ימין מוכן?" – "מוכן!"', '"Starboard side ready?" – "Ready!"'),
        hint: t('שאל את הצוות בצד ימין אם הוא מוכן, והמתן לתשובה "מוכן".', 'Ask the starboard-side crew if they are ready and wait for "Ready".'),
        done: { event: 'crewReport', data: { side: 'starboard', ready: true } },
        optional: true,
        highlight: ['checkStarboardReady'],
        source: 'school',
      },
      {
        id: 'checkPort',
        title: t('"צד שמאל מוכן?" – "מוכן!"', '"Port side ready?" – "Ready!"'),
        hint: t('שאל את הצוות בצד שמאל אם הוא מוכן, והמתן לתשובה "מוכן".', 'Ask the port-side crew if they are ready and wait for "Ready".'),
        done: { event: 'crewReport', data: { side: 'port', ready: true } },
        optional: true,
        highlight: ['checkPortReady'],
        source: 'school',
      },
      {
        id: 'announce',
        title: t('"סיבוב" – התחל לעלות לרוח', '"Tacking" – start heading up'),
        hint: t(`הכרז "סיבוב" וסובב את ההגה ${turn.he} – הסירה מתחילה לעלות לרוח. הצוות עדיין מחזיק את השוטים.`, `Call "Tacking" and turn the wheel ${turn.en} – the boat heads up into the wind. The crew still holds the sheets.`),
        done: { all: [{ command: 'tack' }, { rudderAbs: { min: 8 } }] },
        optional: true,
        highlight: ['tack', 'helm'],
        source: 'school',
      },
      {
        id: 'collapse',
        title: t('המתן לקריסת החלוץ מול הרוח', 'Wait for the jib to collapse head to wind'),
        hint: t('המשך לפנות ברציפות. כשהחרטום חוצה את הרוח החלוץ מאבד את הרוח וקורס – זה הסימן להעביר אותו. אל תעביר לפני כן.', 'Keep turning steadily. As the bow crosses the wind the jib loses its wind and collapses – that is the signal to switch it. Do not switch earlier.'),
        done: JIB_COLLAPSED(target),
        highlight: ['helm'],
        source: 'school',
      },
      {
        id: 'switchJib',
        title: t('"העבר חלוץ!" – צד משחרר, צד מושך', '"Switch jib!" – one side releases, the other pulls'),
        hint: t(`תן פקודה "העבר חלוץ!". הצוות משחרר את השוט ${oldSheet.he} ומושך את השוט ${newSheet.he} כשהחלוץ עובר צד. המשך לפנות עד שהרוח מגיעה מהצד השני (${toName.he}).`, `Command "Switch jib!". The crew releases the ${oldSheet.en} sheet and pulls the ${newSheet.en} one as the jib comes across. Keep turning until the wind is on the other side (${toName.en}).`),
        done: { all: [{ tack: target }, { jibSheet: { side: 'windward', range: { max: 0.1 } } }] },
        highlight: ['switchJib', 'helm'],
        source: 'school',
      },
      {
        id: 'trimNew',
        title: t('מתח את החלוץ לרמה הנכונה', 'Trim the jib to the right tension'),
        hint: t(`ודא מתיחה נכונה של השוט ${newSheet.he}: הטלטלים (חוטי הרוח) זורמים ישר בשני הצדדים, השדרה מתוחה והחלוץ מלא בלי רפרוף. לא יותר מדי – מתיחת יתר סוגרת את המפרש ומאטה.`, `Check the ${newSheet.en} sheet trim: the telltales stream straight on both sides, the luff is tight and the jib full without flutter. No further – over-trimming closes the sail and slows the boat.`),
        done: { jibTrim: { min: 0.7 } },
        holdSeconds: 1,
        highlight: [fromStbd ? 'trimJibStarboard' : 'trimJibPort'],
        source: 'school',
      },
      {
        id: 'settle',
        title: t(`התייצב בקדמית ב${toName.he}`, `Settle close-hauled on ${toName.en}`),
        hint: t('החזר את ההגה למרכז כשהרוח בזווית של כ-45° מהחרטום, וודא שהחלוץ מכוון נכון. המתן שהמהירות תחזור.', 'Centre the wheel when the wind is about 45° off the bow and check the jib trim. Let the speed build.'),
        done: { all: [{ tack: target }, { twaAbs: { min: 35, max: 70 } }, { jibTrim: { min: 0.6 } }, { yawRateAbs: { max: 2.5 } }, { speed: { min: 3.5 } }] },
        holdSeconds: 3,
        highlight: ['helmCenter'],
        source: 'school',
      },
    ],
    success: {
      cond: {
        all: [
          { tack: target },
          { twaAbs: { min: 35, max: 70 } },
          { speed: { min: 3.5 } },
          { jibTrim: { min: 0.55 } },
          { mainTrim: { min: 0.5 } },
          { jibSide: 'leeward' },
          { yawRateAbs: { max: 2.5 } },
        ],
      },
      holdSeconds: 4,
    },
    timeLimit: 100,
    rules: [
      ...safetyRules(),
      {
        id: 'noPrepare',
        type: 'requireBefore',
        event: 'tackChanged',
        require: { command: 'prepareTack' },
        category: 'crew',
        area: 'crew',
        penalty: 20,
        source: 'school',
        message: t('הסיבוב בוצע בלי "היכון לסיבוב".', 'Tacked without "Ready about".'),
        explanation: t('הצוות לא הוכן: השוט החדש לא מוכן על הכננת והשחרור מתעכב.', 'The crew was not prepared: the new sheet was not ready on the winch and the release was late.'),
        suggestion: t('תמיד תן "היכון לסיבוב" והמתן ל"מוכן" לפני הפנייה.', 'Always call "Ready about" and wait for "Ready" before turning.'),
      },
      {
        id: 'noAnnounce',
        type: 'requireBefore',
        event: 'tackChanged',
        require: { command: 'tack' },
        category: 'procedural',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('לא הוכרז "סיבוב".', 'The tack was not called.'),
        explanation: t('הצוות צריך לדעת מתי ההגה מסתובב כדי להיות מוכן להעביר את החלוץ.', 'The crew must know when the helm goes over so they are ready to switch the jib.'),
        suggestion: t('הכרז "סיבוב" ברגע שאתה מתחיל לסובב את ההגה.', 'Call "Tack" as you put the helm over.'),
      },
      {
        id: 'noSideCheck',
        type: 'requireBefore',
        event: 'crewCommand',
        eventData: { command: 'tack' },
        require: { all: [{ event: 'crewReport', data: { side: 'starboard', ready: true } }, { event: 'crewReport', data: { side: 'port', ready: true } }] },
        category: 'crew',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('הכרזת "סיבוב" לפני ששני הצדדים ענו "מוכן".', 'Called "Tacking" before both sides answered "Ready".'),
        explanation: t('הסקיפר מוודא שכל צד מוכן – מי שמשחרר ומי שמושך – לפני שההגה מסתובב.', 'The skipper checks that each side – the one releasing and the one pulling – is ready before the helm goes over.'),
        suggestion: t('שאל "צד ימין מוכן?" ו"צד שמאל מוכן?" והמתן ל"מוכן" מכל צד.', 'Ask "Starboard side ready?" and "Port side ready?" and wait for "Ready" from each.'),
      },
      {
        id: 'earlySwitch',
        type: 'checkAtEvent',
        event: 'crewCommand',
        eventData: { command: 'switchJib' },
        require: JIB_COLLAPSED(target),
        category: 'timing',
        area: 'crew',
        penalty: 15,
        source: 'school',
        message: t('"העבר חלוץ" ניתן לפני שהחלוץ קרס.', '"Switch jib" was called before the jib collapsed.'),
        explanation: t('החלוץ עדיין עבד ונתן כוח. שחרור מוקדם מאבד מהירות לפני מעבר הרוח ומגדיל את הסיכון להיתקע ברוח.', 'The jib was still drawing. Releasing early loses speed before the bow crosses the wind and makes it easier to get stuck in irons.'),
        suggestion: t('המתן עד שהחלוץ מתחיל להתנפנף מול הרוח, ורק אז "העבר חלוץ!".', 'Wait until the jib starts to flap head to wind, then call "Switch jib!".'),
      },
      {
        id: 'noSwitchCall',
        type: 'requireBefore',
        event: 'jibChangedSide',
        require: { command: 'switchJib' },
        category: 'procedural',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('החלוץ הועבר בלי פקודת "העבר חלוץ".', 'The jib was moved across without the "Switch jib" call.'),
        explanation: t('הפקודה מתאמת בין הצד שמשחרר לצד שמושך, כך ששניהם פועלים יחד.', 'The call coordinates the side that releases with the side that pulls so they act together.'),
        suggestion: t('כשהחלוץ קורס – "העבר חלוץ!".', 'When the jib collapses – "Switch jib!".'),
      },
      {
        id: 'lowSpeedStart',
        type: 'checkAtEvent',
        event: 'enteredNoGo',
        require: { speed: { min: 4 } },
        category: 'timing',
        area: 'steering',
        penalty: 10,
        source: 'general',
        message: t('נכנסת לסיבוב במהירות נמוכה.', 'Started the tack with too little speed.'),
        explanation: t('בלי תנופה הסירה עלולה להיעצר בשטח המת ("להיתקע ברוח").', 'Without momentum the boat can stop in the no-go zone ("in irons").'),
        suggestion: t('צבור מהירות בקדמית לפני הסיבוב.', 'Build speed close-hauled before tacking.'),
      },
      {
        id: 'inIrons',
        type: 'forbidEvent',
        event: 'inIrons',
        category: 'steering',
        area: 'steering',
        penalty: 25,
        source: 'general',
        recoverable: true,
        message: t('הסירה נתקעה ברוח (בשטח המת).', 'The boat is stuck in irons.'),
        explanation: t('הסירה עצרה עם החרטום אל הרוח, ובלי מהירות ההגה אינו פועל.', 'The boat stopped head to wind and without speed the rudder has no effect.'),
        suggestion: t('פנה בנחישות וללא עצירה. כדי להיחלץ: החזק את החלוץ בצד הרוח (הפוך) כדי לדחוף את החרטום, והמתן לתנועה.', 'Turn decisively without stopping. To recover: back the jib to push the bow round, then sail away.'),
      },
      {
        id: 'slowTurn',
        type: 'eventGap',
        from: 'enteredNoGo',
        to: 'exitedNoGo',
        maxSeconds: 14,
        category: 'steering',
        area: 'steering',
        penalty: 10,
        source: 'general',
        message: t('הפנייה דרך הרוח הייתה איטית.', 'The turn through the wind was slow.'),
        explanation: t('ככל שהסירה שוהה בשטח המת היא מאבדת יותר מהירות.', 'The longer the boat stays in the no-go zone the more speed it loses.'),
        suggestion: t('השתמש בהגה בזווית גדולה יותר ובפנייה רציפה.', 'Use more rudder and a continuous turn.'),
      },
      {
        id: 'jibBackedAfterTack',
        type: 'condDuration',
        after: 'tackChanged',
        cond: { jibBacked: true },
        seconds: 4,
        category: 'sail',
        area: 'sails',
        penalty: 15,
        source: 'general',
        recoverable: true,
        message: t('החלוץ נשאר הפוך אחרי הסיבוב.', 'The jib stayed aback after the tack.'),
        explanation: t('"העבר חלוץ" ניתן מאוחר (או לא ניתן), ולכן החלוץ נתפס ברוח מהצד הלא נכון ובולם את הסירה.', 'The "Switch jib" call came late (or not at all), so the jib is held on the wrong side and brakes the boat.'),
        suggestion: t('תן "העבר חלוץ!" ברגע שהחלוץ קורס מול הרוח.', 'Call "Switch jib!" as soon as the jib collapses head to wind.'),
      },
      {
        id: 'lateTrim',
        type: 'condDuration',
        after: 'tackChanged',
        cond: { all: [{ jibLuff: { min: 0.6 } }, { twaAbs: { min: 30 } }] },
        seconds: 8,
        category: 'timing',
        area: 'crew',
        penalty: 10,
        source: 'general',
        message: t('השוט החדש נמתח מאוחר.', 'The new sheet was trimmed late.'),
        explanation: t('עד שהחלוץ נמתח בצד החדש הסירה כמעט ללא כוח הנעה.', 'Until the jib is trimmed on the new side the boat has little drive.'),
        suggestion: t('אחרי "העבר חלוץ" מתח את השוט החדש מיד כשהחלוץ עובר צד.', 'After "Switch jib", trim the new sheet as soon as the jib comes across.'),
      },
      {
        id: 'overshoot',
        type: 'condDuration',
        after: 'tackChanged',
        cond: { twaAbs: { min: 85, max: 179 } },
        seconds: 3,
        category: 'steering',
        area: 'steering',
        penalty: 10,
        source: 'general',
        message: t('פנית רחוק מדי אחרי הסיבוב.', 'Turned too far after the tack.'),
        explanation: t('המטרה היא להתייצב בקדמית במפנה החדש, לא לרדת לצד או לגבית.', 'The goal is to settle close-hauled on the new tack, not to bear away to a reach.'),
        suggestion: t('התחל להחזיר את ההגה למרכז כבר כשהרוח עוברת את החרטום.', 'Start centring the wheel as the wind crosses the bow.'),
      },
      {
        id: 'wrongWay',
        type: 'forbidEvent',
        event: 'tackChanged',
        eventData: { through: 'stern' },
        category: 'procedural',
        area: 'completion',
        penalty: 30,
        source: 'general',
        message: t('החלפת מפנה דרך הירכתיים – זה מהפך, לא סיבוב.', 'You changed tack through the stern – that is a gybe, not a tack.'),
        explanation: t('בסיבוב החרטום עובר דרך הרוח. פנייה הפוכה מביאה למהפך.', 'In a tack the bow goes through the wind. Turning the other way causes a gybe.'),
        suggestion: t(`בסיבוב מ${fromName.he} פנה ${turn.he}.`, `When tacking from ${fromName.en}, turn ${turn.en}.`),
      },
    ],
    commonErrors: [
      t('פנייה איטית מדי ונתקעות ברוח.', 'Turning too slowly and getting stuck in irons.'),
      t('"העבר חלוץ" מוקדם מדי, לפני שהחלוץ קרס – איבוד מהירות.', 'Calling "Switch jib" before the jib collapses – lost speed.'),
      t('"העבר חלוץ" מאוחר מדי – החלוץ הפוך ובולם.', 'Calling "Switch jib" too late – the jib is aback and brakes the boat.'),
      t('הכרזת "סיבוב" לפני ששני הצדדים ענו "מוכן".', 'Calling "Tacking" before both sides answered "Ready".'),
      t('פנייה רחוקה מדי במפנה החדש.', 'Overshooting the new close-hauled course.'),
      t('סיבוב בלי להכין את הצוות.', 'Tacking without preparing the crew.'),
    ],
    review: {
      status: 'needsInstructorReview',
      notes: [REVIEW_NOTE, 'Command sequence given by the project owner (2026-11-27): "הצוות היכון לסיבוב" → "צד ימין מוכן?" "מוכן" → "צד שמאל מוכן?" "מוכן" → "סיבוב" (head up) → wait for the jib to collapse head to wind → "העבר חלוץ!" (one side releases, the other pulls) → trim the jib → settle close-hauled. Still to be confirmed by a qualified instructor.', 'Traveller and main trim through the tack are not modelled.'],
    },
  };
}
