import type { ScenarioDef } from './types';
import { REVIEW_NOTE, safetyRules, t, type Dir } from './common';

export function buildTack(dir: Dir = 'starboardToPort'): ScenarioDef {
  const fromStbd = dir === 'starboardToPort';
  const target = fromStbd ? 'port' : 'starboard';
  const turn = fromStbd ? t('ימינה', 'to starboard') : t('שמאלה', 'to port');
  const fromName = fromStbd ? t('מפנה ימני', 'starboard tack') : t('מפנה שמאלי', 'port tack');
  const toName = fromStbd ? t('מפנה שמאלי', 'port tack') : t('מפנה ימני', 'starboard tack');
  const oldSheet = fromStbd ? t('השמאלי', 'port') : t('הימני', 'starboard');
  const newSheet = fromStbd ? t('הימני', 'starboard') : t('השמאלי', 'port');
  return {
    id: 'tack',
    variant: dir,
    title: t('סיבוב', 'Tacking'),
    objective: t(`עליך לבצע סיבוב מ${fromName.he} ל${toName.he}.`, `Tack from ${fromName.en} to ${toName.en}.`),
    learningObjective: t(
      'בסיבוב החרטום עובר דרך הרוח. נדרשת מהירות ופנייה רציפה כדי לחצות את השטח המת, והחלוץ מועבר לצד החדש.',
      'In a tack the bow passes through the wind. You need speed and a steady turn to cross the no-go zone, and the jib is moved to the new side.',
    ),
    initial: {
      heading: 0,
      speed: 5.5,
      wind: { trueFrom: fromStbd ? 45 : 315, trueSpeed: 12 },
      mainHoist: 1,
      mainsheet: 0.9,
      jibDeployed: 1,
      jibPortSheet: fromStbd ? 1 : 0,
      jibStarboardSheet: fromStbd ? 0 : 1,
      autoTrim: true,
    },
    steps: [
      {
        id: 'prepare',
        title: t('הכן את הצוות', 'Prepare the crew'),
        hint: t('תן פקודה "היכון לסיבוב" והמתן שהצוות ידווח "מוכן".', 'Command "Ready about" and wait for the crew to report ready.'),
        done: { crewReady: 'tack' },
        optional: true,
        highlight: ['prepareTack'],
        source: 'school',
      },
      {
        id: 'announce',
        title: t('הכרז "סיבוב" והתחל לפנות', 'Call "Tacking" and start the turn'),
        hint: t(`תן פקודה "סיבוב" וסובב את ההגה ${turn.he} – אל הרוח.`, `Command "Tack" and turn the wheel ${turn.en} – into the wind.`),
        done: { all: [{ command: 'tack' }, { rudderAbs: { min: 8 } }] },
        optional: true,
        highlight: ['tack', 'helm'],
        source: 'school',
      },
      {
        id: 'intoWind',
        title: t('פנה אל הרוח', 'Turn into the wind'),
        hint: t('שמור על פנייה רציפה. אל תעצור בשטח המת – הסירה מאבדת מהירות.', 'Keep turning steadily. Do not stop in the no-go zone – the boat loses speed.'),
        done: { twaAbs: { max: 15 } },
        highlight: ['helm'],
        source: 'general',
      },
      {
        id: 'cross',
        title: t('עבור את קו הרוח', 'Cross the wind'),
        hint: t(`המשך לפנות עד שהרוח תגיע מהצד השני (${toName.he}).`, `Keep turning until the wind is on the other side (${toName.en}).`),
        done: { all: [{ tack: target }, { twaAbs: { min: 10 } }] },
        highlight: ['helm'],
        source: 'general',
      },
      {
        id: 'release',
        title: t(`שחרר את שוט החלוץ ${oldSheet.he}`, `Release the old (${oldSheet.en}) jib sheet`),
        hint: t('הצוות משחרר אוטומטית אחרי פקודת "סיבוב". אם לא נתת – שחרר בעצמך.', 'The crew releases it after the "Tack" command. If you did not give it – release it yourself.'),
        done: { jibSheet: { side: 'windward', range: { max: 0.1 } } },
        highlight: [fromStbd ? 'releaseJibPort' : 'releaseJibStarboard'],
        source: 'general',
      },
      {
        id: 'trimNew',
        title: t(`מתח את שוט החלוץ ${newSheet.he}`, `Trim the new (${newSheet.en}) jib sheet`),
        hint: t('מתח את החלוץ בצד החדש עד שהוא מלא.', 'Trim the jib on the new side until it is full.'),
        done: { jibTrim: { min: 0.6 } },
        highlight: [fromStbd ? 'trimJibStarboard' : 'trimJibPort'],
        source: 'general',
      },
      {
        id: 'settle',
        title: t('התייצב בקדמית', 'Settle close-hauled'),
        hint: t('החזר את ההגה למרכז כשהרוח בזווית של כ-45° מהחרטום, והמתן שהמהירות תחזור.', 'Centre the wheel when the wind is about 45° off the bow and let the speed build.'),
        done: { all: [{ tack: target }, { twaAbs: { min: 35, max: 70 } }, { yawRateAbs: { max: 2.5 } }, { speed: { min: 3.5 } }] },
        holdSeconds: 3,
        highlight: ['helmCenter'],
        source: 'general',
      },
    ],
    success: {
      cond: {
        all: [
          { tack: target },
          { twaAbs: { min: 35, max: 70 } },
          { speed: { min: 3.5 } },
          { jibTrim: { min: 0.55 } },
          { mainTrim: { min: 0.5 } },
          { jibSide: 'leeward' },
          { yawRateAbs: { max: 2.5 } },
        ],
      },
      holdSeconds: 4,
    },
    timeLimit: 100,
    rules: [
      ...safetyRules(),
      {
        id: 'noPrepare',
        type: 'requireBefore',
        event: 'tackChanged',
        require: { command: 'prepareTack' },
        category: 'crew',
        area: 'crew',
        penalty: 20,
        source: 'school',
        message: t('הסיבוב בוצע בלי "היכון לסיבוב".', 'Tacked without "Ready about".'),
        explanation: t('הצוות לא הוכן: השוט החדש לא מוכן על הכננת והשחרור מתעכב.', 'The crew was not prepared: the new sheet was not ready on the winch and the release was late.'),
        suggestion: t('תמיד תן "היכון לסיבוב" והמתן ל"מוכן" לפני הפנייה.', 'Always call "Ready about" and wait for "Ready" before turning.'),
      },
      {
        id: 'noAnnounce',
        type: 'requireBefore',
        event: 'tackChanged',
        require: { command: 'tack' },
        category: 'procedural',
        area: 'crew',
        penalty: 10,
        source: 'school',
        message: t('לא הוכרז "סיבוב".', 'The tack was not called.'),
        explanation: t('הצוות צריך לדעת מתי ההגה מסתובב כדי לשחרר את החלוץ בזמן הנכון.', 'The crew must know when the helm goes over so they can release the jib at the right moment.'),
        suggestion: t('הכרז "סיבוב" ברגע שאתה מתחיל לסובב את ההגה.', 'Call "Tack" as you put the helm over.'),
      },
      {
        id: 'lowSpeedStart',
        type: 'checkAtEvent',
        event: 'enteredNoGo',
        require: { speed: { min: 4 } },
        category: 'timing',
        area: 'steering',
        penalty: 10,
        source: 'general',
        message: t('נכנסת לסיבוב במהירות נמוכה.', 'Started the tack with too little speed.'),
        explanation: t('בלי תנופה הסירה עלולה להיעצר בשטח המת ("להיתקע ברוח").', 'Without momentum the boat can stop in the no-go zone ("in irons").'),
        suggestion: t('צבור מהירות בקדמית לפני הסיבוב.', 'Build speed close-hauled before tacking.'),
      },
      {
        id: 'inIrons',
        type: 'forbidEvent',
        event: 'inIrons',
        category: 'steering',
        area: 'steering',
        penalty: 25,
        source: 'general',
        recoverable: true,
        message: t('הסירה נתקעה ברוח (בשטח המת).', 'The boat is stuck in irons.'),
        explanation: t('הסירה עצרה עם החרטום אל הרוח, ובלי מהירות ההגה אינו פועל.', 'The boat stopped head to wind and without speed the rudder has no effect.'),
        suggestion: t('פנה בנחישות וללא עצירה. כדי להיחלץ: החזק את החלוץ בצד הרוח (הפוך) כדי לדחוף את החרטום, והמתן לתנועה.', 'Turn decisively without stopping. To recover: back the jib to push the bow round, then sail away.'),
      },
      {
        id: 'slowTurn',
        type: 'eventGap',
        from: 'enteredNoGo',
        to: 'exitedNoGo',
        maxSeconds: 14,
        category: 'steering',
        area: 'steering',
        penalty: 10,
        source: 'general',
        message: t('הפנייה דרך הרוח הייתה איטית.', 'The turn through the wind was slow.'),
        explanation: t('ככל שהסירה שוהה בשטח המת היא מאבדת יותר מהירות.', 'The longer the boat stays in the no-go zone the more speed it loses.'),
        suggestion: t('השתמש בהגה בזווית גדולה יותר ובפנייה רציפה.', 'Use more rudder and a continuous turn.'),
      },
      {
        id: 'jibBackedAfterTack',
        type: 'condDuration',
        after: 'tackChanged',
        cond: { jibBacked: true },
        seconds: 4,
        category: 'sail',
        area: 'sails',
        penalty: 15,
        source: 'general',
        recoverable: true,
        message: t('החלוץ נשאר הפוך אחרי הסיבוב.', 'The jib stayed aback after the tack.'),
        explanation: t('השוט הישן לא שוחרר ולכן החלוץ נתפס ברוח מהצד הלא נכון ובולם את הסירה.', 'The old sheet was not released so the jib is held on the wrong side and brakes the boat.'),
        suggestion: t('שחרר את השוט הישן כשהחרטום עובר את הרוח.', 'Release the old sheet as the bow passes through the wind.'),
      },
      {
        id: 'lateTrim',
        type: 'condDuration',
        after: 'tackChanged',
        cond: { all: [{ jibLuff: { min: 0.6 } }, { twaAbs: { min: 30 } }] },
        seconds: 8,
        category: 'timing',
        area: 'crew',
        penalty: 10,
        source: 'general',
        message: t('השוט החדש נמתח מאוחר.', 'The new sheet was trimmed late.'),
        explanation: t('עד שהחלוץ נמתח בצד החדש הסירה כמעט ללא כוח הנעה.', 'Until the jib is trimmed on the new side the boat has little drive.'),
        suggestion: t('תן "מתח חלוץ" בצד החדש מיד אחרי שהחלוץ עובר.', 'Trim the new jib sheet as soon as the jib crosses.'),
      },
      {
        id: 'overshoot',
        type: 'condDuration',
        after: 'tackChanged',
        cond: { twaAbs: { min: 85, max: 179 } },
        seconds: 3,
        category: 'steering',
        area: 'steering',
        penalty: 10,
        source: 'general',
        message: t('פנית רחוק מדי אחרי הסיבוב.', 'Turned too far after the tack.'),
        explanation: t('המטרה היא להתייצב בקדמית במפנה החדש, לא לרדת לצד או לגבית.', 'The goal is to settle close-hauled on the new tack, not to bear away to a reach.'),
        suggestion: t('התחל להחזיר את ההגה למרכז כבר כשהרוח עוברת את החרטום.', 'Start centring the wheel as the wind crosses the bow.'),
      },
      {
        id: 'wrongWay',
        type: 'forbidEvent',
        event: 'tackChanged',
        eventData: { through: 'stern' },
        category: 'procedural',
        area: 'completion',
        penalty: 30,
        source: 'general',
        message: t('החלפת מפנה דרך הירכתיים – זה מהפך, לא סיבוב.', 'You changed tack through the stern – that is a gybe, not a tack.'),
        explanation: t('בסיבוב החרטום עובר דרך הרוח. פנייה הפוכה מביאה למהפך.', 'In a tack the bow goes through the wind. Turning the other way causes a gybe.'),
        suggestion: t(`בסיבוב מ${fromName.he} פנה ${turn.he}.`, `When tacking from ${fromName.en}, turn ${turn.en}.`),
      },
    ],
    commonErrors: [
      t('פנייה איטית מדי ונתקעות ברוח.', 'Turning too slowly and getting stuck in irons.'),
      t('אי-שחרור השוט הישן – החלוץ הפוך.', 'Not releasing the old sheet – jib aback.'),
      t('פנייה רחוקה מדי במפנה החדש.', 'Overshooting the new close-hauled course.'),
      t('סיבוב בלי להכין את הצוות.', 'Tacking without preparing the crew.'),
    ],
    review: {
      status: 'needsInstructorReview',
      notes: [REVIEW_NOTE, 'Command sequence ("היכון לסיבוב" → "מוכן" → "סיבוב") follows common practice; exact wording may differ between schools.', 'Traveller and main trim through the tack are not modelled.'],
    },
  };
}
